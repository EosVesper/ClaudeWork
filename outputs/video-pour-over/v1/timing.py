"""练习 5《一杯手冲咖啡》时间轴：render.py、prep.sh 的参数和 audio.py 共用。
100 BPM，一拍 0.6 秒；每个镜头占整数拍，所有切换都落在拍子上。"""
BPM = 100
BEAT = 60 / BPM
# (镜头, 拍数, 素材起点秒, 素材用多长秒, 大字, 小字)
# 素材用多长 / (拍数*BEAT) = 播放速度：<1 是慢放（补帧），>1 是快放
SHOTS = [
    ("c1", 4, 0.0, 1.2, "手冲咖啡", "从豆子到杯子"),      # 只用前 1.2 秒：之后窗边冒出怪烟
    ("c2", 2, 0.0, 1.2, "15 g", "咖啡豆"),
    ("c3", 2, 1.0, 1.2, "中细研磨", "像粗砂糖"),
    ("c4", 4, 0.4, 4.8, "92°C", "先闷蒸 30 秒"),          # 2 倍速，看粉层鼓起来
    ("c5", 4, 0.0, 2.4, "1 : 15", "粉水比"),
    ("c6", 4, 0.0, 2.4, "倒一杯", ""),
    ("c7", 4, 0.0, 1.0, "趁热", ""),                      # 只用前 1 秒：之后蒸汽变成卡通烟圈
    ("c8", 8, 0.0, 0.7, "", ""),                          # 只用前 0.7 秒，之后定格压暗出片尾
]
DUR = [n * BEAT for _, n, *_ in SHOTS]
ST = [0.0]
for d in DUR: ST.append(ST[-1] + d)
TOTAL = ST[-1]
END_AT = ST[7] + 2 * BEAT        # 片尾字出现的时间
