"""练习 5《一杯手冲咖啡》v2 舒缓版时间轴：prep.sh、render.py、audio.py 共用。
一拍 0.9 秒（约 67 BPM），镜头之间用 0.7 秒叠化，镜头切换仍落在拍子上，但没有鼓点去强调它。"""
BEAT = 0.9
XF = 0.7          # 叠化时长；每个镜头会提前 XF 秒开始，用来和上一镜重叠
# (镜头, 拍数, 素材起点秒, 素材用多长秒, 大字, 小字)
# 播放速度 = 素材用多长 / (拍数*BEAT + XF)，小于 1 是慢放（补帧）
SHOTS = [
    ("c1", 4, 0.0, 1.2, "手冲咖啡", "从豆子到杯子"),      # 只用前 1.2 秒：之后窗边冒出怪烟
    ("c2", 3, 0.0, 2.0, "15 g", "咖啡豆"),
    ("c3", 3, 1.0, 2.2, "中细研磨", "像粗砂糖"),
    ("c4", 4, 0.4, 5.6, "92°C", "先闷蒸 30 秒"),          # 略快放，看粉层慢慢鼓起来
    ("c5", 4, 0.0, 3.2, "1 : 15", "粉水比"),
    ("c6", 4, 0.0, 3.2, "倒一杯", ""),
    ("c7", 4, 0.0, 1.5, "趁热", ""),                      # 只用前 1.5 秒：之后蒸汽变成卡通烟圈
    ("c8", 6, 0.0, 0.7, "", ""),                          # 只用前 0.7 秒，慢放后定格，压暗出片尾
]
C8_PLAY = 3.0     # C8 的 0.7 秒素材慢放成 3 秒，之后停在最后一帧
DUR = [n * BEAT for _, n, *_ in SHOTS]
ST = [0.0]
for d in DUR: ST.append(ST[-1] + d)
TOTAL = ST[-1]
END_AT = ST[7] + 1.6            # 片尾字出现的时间

def speed(i):
    name, n, ss, use, *_ = SHOTS[i]
    return use / (C8_PLAY if name == "c8" else n * BEAT + XF)
