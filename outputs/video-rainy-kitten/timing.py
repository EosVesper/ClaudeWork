"""时间轴：render.py 和 audio.py 共用。
配音原片只有 15.8 秒（5 句连着念），这里按句切开，重新摆到 25.7 秒的时间轴上，
让每句话落在对应镜头里，句间留出只有雨声和音乐的空隙。
"""
# 5 个镜头的时长（秒）。S5 包含片尾标题。
# v2：S2、S3 只用素材里没出问题的一小段并放慢，所以这两镜缩短了
DUR = [6.0, 3.3, 4.6, 4.8, 7.0]
# 每个镜头开头与上一镜的叠化时长；S4→S5（"后来"）用更长的叠化表示时间流逝
XF = [0.0, 0.4, 0.4, 0.3, 0.9]
ST = [0.0]
for d in DUR: ST.append(ST[-1] + d)
TOTAL = ST[-1]
TITLE_AT = 23.4

# 配音里每个分句的起止（ffmpeg silencedetect=noise=-35dB:d=0.25 量出来的）
SEG = [(0.324, 0.955, "下雨了"), (1.433, 2.749, "小橘猫缩在纸箱里"), (3.108, 3.922, "哪儿也去不了"),
       (4.370, 5.477, "对面的窗户亮着灯"), (5.815, 6.683, "看起来很暖"),
       (7.198, 7.609, "忽然"), (7.943, 8.842, "一把黄色的伞"), (9.118, 10.075, "停在了它面前"),
       (10.543, 11.035, "一只手"), (11.322, 12.388, "轻轻地伸了过来"),
       (12.850, 13.252, "后来"), (13.614, 14.400, "每到下雨天"), (14.740, 15.840, "它都睡得特别香")]
# 5 句话：(包含的分句下标, 这句话在成片里开口的时间)
SENT = [((0, 1, 2), 1.3), ((3, 4), 6.6), ((5, 6, 7), 9.9), ((8, 9), 14.9), ((10, 11, 12), 19.8)]
PAD = 0.12   # 切配音时句子前后各留一点

# (在原配音里的切点起, 止, 放到成片的时间)
VOICE = []
CAPS = []
for idx, at in SENT:
    a, b = SEG[idx[0]][0], SEG[idx[-1]][1]
    VOICE.append((a - PAD, b + PAD, at - PAD))
    for k in idx:
        s, e, text = SEG[k]
        CAPS.append((at + s - a - 0.05, at + e - a + 0.15, text))

if __name__ == "__main__":
    print("total", TOTAL, ST)
    for v in VOICE: print("voice", [round(x, 2) for x in v])
    for c in CAPS: print("cap", round(c[0], 2), round(c[1], 2), c[2])
