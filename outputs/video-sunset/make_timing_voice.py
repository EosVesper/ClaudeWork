"""有配音后：按 silencedetect 实测的 19 段语音重排时间轴。"""
import json

# 语音段（起, 止），来自 silencedetect noise=-35dB d=0.12
SEG = [(0.36, 1.20), (1.49, 2.41), (2.85, 4.10), (4.50, 5.74), (6.15, 6.88),
       (7.23, 7.97), (8.40, 8.83), (9.18, 11.40), (11.78, 12.71), (13.10, 13.65),
       (14.10, 15.10), (15.47, 16.79), (17.17, 17.64), (18.01, 19.32), (19.71, 21.03),
       (21.35, 22.17), (22.66, 23.03), (23.20, 24.52), (24.89, 26.21)]
s = lambda i: SEG[i][0]
e = lambda i: SEG[i][1]
mid8 = s(7) + (e(7) - s(7)) * 5 / 13   # "短波的蓝光|最容易被空气撞散" 在第 8 段内按字数切开

# 字幕条：(开始说话的时刻, 文本)
CH = [(s(0), "傍晚的天空"), (s(1), "为什么会烧起来？"),
      (s(2), "阳光看起来是白的"), (s(3), "其实混着所有颜色"), (s(4), "颜色不同，波长就不同"),
      (s(6), "白天，短波的蓝光"), (mid8, "最容易被空气撞散"), (s(8), "天就成了蓝色"),
      (s(9), "到了傍晚，阳光斜着进来"), (s(11), "要穿过厚得多的大气"),
      (s(12), "一路上，蓝光几乎被散光了"),
      (s(14), "剩下的红光和橙光"), (s(15), "把云染成了火"),
      (s(16), "所以晚霞不是云在变色"), (s(18), "是空气在替你筛光")]
LAST_END = e(18)

caps = []
for k, (t0, txt) in enumerate(CH):
    t1 = CH[k + 1][0] - 0.02 if k + 1 < len(CH) else LAST_END + 0.35
    caps.append([round(t0 - 0.05, 3), round(t1, 3), txt])

# 换图时刻：落在该场景第一句开口前的停顿里（叠化 0.4s 正好在停顿中完成）
B = [0, s(2), s(6), s(9), s(12), s(14), s(16), LAST_END + 0.9]
B = [0] + [b + 0.05 for b in B[1:-1]] + [B[-1]]
scene_dur = [round(B[k + 1] - B[k], 3) for k in range(7)]
json.dump({"scene_dur": scene_dur, "end_dur": 2.6, "captions": caps, "out": "sunset_video.mp4"},
          open("timing.json", "w"), ensure_ascii=False, indent=1)
print(scene_dur, round(B[-1] + 2.6, 2))
for c in caps: print(c)
